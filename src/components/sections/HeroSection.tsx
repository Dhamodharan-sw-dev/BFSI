function AppRootAppFwWidget() {
  const [regNumber, setRegNumber] = useState("")
  const [mobileNumber, setMobileNumber] = useState("")
  const [message, setMessage] = useState<{
    type: "error" | "success"
    text: string
  } | null>(null)

  function handleSubmit() {
    if (!regNumber.trim()) {
      setMessage({
        type: "error",
        text: "Please enter your vehicle registration number.",
      })
      return
    }
    if (mobileNumber.length !== 10) {
      setMessage({
        type: "error",
        text: "Please enter a valid 10-digit mobile number.",
      })
      return
    }
    setMessage({
      type: "success",
      text: `Thanks! We'll send your quote to your mobile number ending in ${mobileNumber.slice(-4)} shortly.`,
    })
  }

  return (
    <div
      className="content-stretch flex flex-col items-start w-full relative shrink-0"
      data-name="app-root → app-fw-widget"
    >
      <DivIlInputBlock value={regNumber} onChange={setRegNumber} />
      <DivIlInputBlock1 value={mobileNumber} onChange={setMobileNumber} />
      <DivUiSubmitBtn onSubmit={handleSubmit} message={message} />
      <DivFormGroup />
      <DivFormGroup1 />
    </div>
  )
}

